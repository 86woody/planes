// Generates src/generated/*.ts from schemas/*.schema.json.
// Usage: node scripts/generate.mjs [outDir]   (default: src/generated)
import { compile } from "json-schema-to-typescript";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMAS = path.join(PKG, "schemas");
const DEFAULT_OUT = path.join(PKG, "src", "generated");
const PREFIX = "https://mission-control.local/contracts/";
const FILES = ["session", "ingest", "api", "config", "bridge"];

const OPTIONS = {
  bannerComment: "// GENERATED by scripts/generate.mjs. Do not edit.",
  additionalProperties: false,
  unreachableDefinitions: true,
  // D-56: bounded arrays stay plain arrays (the default emits a union of tuples up to 20 long).
  maxItems: -1,
  cwd: SCHEMAS + path.sep,
  $refOptions: {
    resolve: {
      // Refs to sibling schemas (relative, or https://mission-control.local/contracts/<f>)
      // are served from schemas/<f>.
      file: {
        order: 1,
        canRead: (file) => file.url.startsWith(PREFIX) || file.url.includes("/schemas/"),
        read: (file) => {
          const name = path.basename(decodeURIComponent(file.url.replace(/^file:\/\/\/?/, "")));
          return readFileSync(path.join(SCHEMAS, name), "utf8");
        },
      },
    },
  },
};

function loadSchema(name) {
  return JSON.parse(readFileSync(path.join(SCHEMAS, `${name}.schema.json`), "utf8"));
}

// Names a generated file must declare for every $defs entry of a schema.
function declaredNames(src) {
  return new Set([...src.matchAll(/^export (?:interface|type|enum) (\w+)/gm)].map((m) => m[1]));
}

// Fallback for schemas with no root type (api, bridge): compile a copy whose root is an anyOf
// over every $defs name, so json-schema-to-typescript emits every named type. Only used when
// the plain compile does not declare all $defs. The schema file itself is never changed.
function anyOfRootCopy(schema) {
  const names = Object.keys(schema.$defs ?? {});
  const copy = JSON.parse(JSON.stringify(schema));
  copy.anyOf = names.map((n) => ({ $ref: `#/$defs/${n}` }));
  return copy;
}

export async function generate(outDir = DEFAULT_OUT, log = () => {}) {
  mkdirSync(outDir, { recursive: true });
  const report = {};
  for (const name of FILES) {
    const schema = loadSchema(name);
    let ts = await compile(schema, schema.title ?? name, OPTIONS);
    const wanted = Object.keys(schema.$defs ?? {});
    const missing = wanted.filter((n) => !declaredNames(ts).has(n));
    report[name] = "plain";
    if (missing.length > 0) {
      ts = await compile(anyOfRootCopy(schema), schema.title ?? name, OPTIONS);
      report[name] = `anyOf-root (plain compile lacked: ${missing.join(", ")})`;
    }
    writeFileSync(path.join(outDir, `${name}.ts`), ts);
    log(`${name}: ${report[name]}`);
  }
  return report;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const out = process.argv[2] ? path.resolve(process.argv[2]) : DEFAULT_OUT;
  await generate(out, (line) => console.log(line));
}
